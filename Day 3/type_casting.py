# Typecasting

# Mainly Three Types of Datatype
# i)int
# ii)float
# iii)string

# Convert int to str

user_num=45
x=str(user_num)
print(user_num)
print(type(x))

# Convert str to int

Age="45"
y=int(Age)
print(Age)
print(type(y))

# Convert float to str

price=56.09
z=str(price)
print(price)
print(type(z))