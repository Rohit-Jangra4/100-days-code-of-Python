# Escape Squences in Python are used to represent special characters in strings. They are preceded by a backslash (\) and allow you to include characters that would otherwise be difficult or impossible to type directly into a string. Here are some common escape sequences in Python:
# \n - New Line
# \t - Tab
# \r - Carriage Return
# \' - Single Quote
# \" - Double Quote
# \\ - Backslash

# Example of Escape Sequences in Python

# New Line
print("Hello\nWorld")  # Output: Hello (new line) World

# Tab
print("Hello\tWorld")  # Output: Hello (tab) World

# Carriage Return
print("Hello\rWorld")  # Output: World (overwrites Hello)

# Single Quote
print('It\'s a beautiful day!')  # Output: It's a beautiful day!

# Double Quote
print("python is a \"great\" programming language.")  # Output: Python is a "great" programming language.

# Backslash
print("This is a backslash: \\")  # Output: This is a backslash: \

print("Name:Rahul\tSharma\nAge:25\nCity:Delhi")  # Output: Name: Rahul(tab)Sharma (new line) Age: 25 (new line) City: Delhi
